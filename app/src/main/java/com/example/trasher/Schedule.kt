    /**
     * Returns the next pickup we should notify for (PAPER/COM/GPN/GCN only),
     * where the alarm time for the given reminder setting is still in the future.
     */
    fun nextNotifiablePickup(time: ReminderSettings.Time): Pair<String, ScheduleEntry>? {
        val now = Calendar.getInstance()
        for ((dateKey, entry) in data.entries.sortedBy { it.key }) {
            if (entry.type !in NOTIFIABLE_TYPES) continue
            if (alarmCalFor(dateKey, time).after(now)) return Pair(dateKey, entry)
        }
        return null
    }

    /** Returns a Calendar set to the reminder time on (or the day before) the given date key. */
    fun alarmCalFor(dateKey: String, time: ReminderSettings.Time): Calendar {
        val (y, m, d) = dateKey.split("-").map { it.toInt() }
        return Calendar.getInstance().apply {
            set(y, m - 1, d, time.hour, time.minute, 0)
            set(Calendar.MILLISECOND, 0)
            if (time.dayBefore) add(Calendar.DAY_OF_YEAR, -1)
        }
    }
